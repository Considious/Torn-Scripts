import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {performance} from 'node:perf_hooks';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('./src/00-target-records.part',import.meta.url),'utf8'),context);
const factory=context.SLINK_PDA_TARGET_RECORDS,clone=value=>JSON.parse(JSON.stringify(value));
const native=new Map();let id=0,fail=false,partial=false,hold;
const write=async request=>{
 if(hold)await hold;
 if(fail)throw Error('QuotaExceeded');
 let count=0;
 for(const op of request.ops){native.set(op.id,clone(op));if(partial&&++count===1){partial=false;throw Error('Interrupted');}}
 return{ops:clone([...native.values()])};
};
const page=(legacy={},snapshot={ops:clone([...native.values()])})=>factory.create({snapshot,legacy,write,id:()=>`test:${++id}`});
const first=page({'1':{name:'A',description:'old',tags:['Target']},'2':{name:'B'}});await first.ready;
assert.equal(native.size,3);const b=page();await b.ready;
await Promise.all([first.change('patch',1,first.snapshot()['1'],{...first.snapshot()['1'],description:'new note'}),b.change('patch',1,b.snapshot()['1'],{...b.snapshot()['1'],name:'new name'})]);
await first.refresh();assert.equal(first.snapshot()['1'].description,'new note');assert.equal(first.snapshot()['1'].name,'new name');
const stale=page();await stale.ready;
await first.change('remove',1);await assert.rejects(stale.change('patch',1,stale.snapshot()['1'],{...stale.snapshot()['1'],description:'stale edit'}),/deleted/);
assert.equal(page().snapshot()['1'],undefined,'Deleted targets must not resurrect from stale views');
const staleAdd=page();await staleAdd.ready;
await first.refresh();await first.change('add',1,{}, {name:'Explicit re-add'});
assert.equal(page().snapshot()['1'].name,'Explicit re-add');
await first.change('remove',1);
await staleAdd.change('add',1,{}, {name:'Before newer deletion'});
assert.equal(page().snapshot()['1'],undefined,'A re-add which did not observe every tombstone stays deleted');
fail=true;const quota=page();await quota.ready;
await assert.rejects(quota.change('patch',2,quota.snapshot()['2'],{name:'B',description:'retained draft'}),/Quota/);
assert.equal(quota.status().pending,1);await assert.rejects(quota.flush(),/Quota/);
fail=false;await quota.retry();await quota.flush();assert.equal(page().snapshot()['2'].description,'retained draft');
native.clear();partial=true;const migration=page({'3':{name:'C'},'4':{name:'D'}});
await assert.rejects(migration.ready,/Interrupted/);await migration.retry();assert.equal(native.size,3,'Interrupted migration is idempotent on retry');
await migration.change('remove',3);const repeated=page({'3':{name:'stale recovery'},'4':{name:'old'}});await repeated.ready;assert.equal(repeated.snapshot()['3'],undefined);
const missing=page({'8':{name:'preserved legacy'}},{error:'Read failed',ops:[]});await assert.rejects(missing.flush(),/Read failed/);assert.equal(missing.snapshot()['8'].name,'preserved legacy');assert.throws(()=>missing.change('add',9,{},{}),/Read failed/);
assert.throws(()=>factory.project([{schema:99}]),/Unsupported/);
assert.throws(()=>migration.replace({'-1':{name:'bad'}}),/Invalid/);
assert.equal(page().snapshot()['4'].name,'D');
const before=clone([...native.values()]);
const unconfirmed=factory.create({snapshot:{ops:before},write:async()=>({ops:before}),id:()=>`test:${++id}`});
await assert.rejects(unconfirmed.change('patch',4,{name:'D'},{name:'Unconfirmed'}),/retain every/);assert.equal(unconfirmed.status().pending,1);
native.clear();const legacy=Object.fromEntries(Array.from({length:1000},(_,index)=>[String(index+1),{name:`Player ${index}`,description:'Keep this note',tags:['Target']}]));
const start=performance.now(),large=page(legacy);await large.ready;const elapsed=performance.now()-start;
assert.equal(Object.keys(large.snapshot()).length,1000);assert.ok(elapsed<3000,`1000-target migration took ${elapsed}ms`);
console.log(`Target journal: independent edits, deletion/re-add, stale resurrection, failed/partial writes, migration, corruption and 1000 targets passed (${elapsed.toFixed(1)}ms; ${JSON.stringify([...native.values()]).length} bytes).`);
