import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('./src/00-torn-theme.part',import.meta.url),'utf8');
const context=vm.createContext({URL});
vm.runInContext(fs.readFileSync(new URL('./src/00-torn-theme-variables.part',import.meta.url),'utf8'),context);
vm.runInContext(fs.readFileSync(new URL('./src/00-torn-theme-pages.part',import.meta.url),'utf8'),context);
vm.runInContext(source,context);
const api=context.SLINK_TORN_THEME;
const pageRules=context.SLINK_TORN_PAGE_RULES;
assert.equal(pageRules.groups.length,9);
assert.ok(pageRules.groups.some(group=>group.selector.includes('#travel-root')));
assert.ok(pageRules.groups.some(group=>group.selector.includes('#attack-root')));
assert.ok(pageRules.groups.some(group=>group.selector.includes('Attack log')));
assert.ok(pageRules.groups.some(group=>group.selector.includes('.crimes-app')));
assert.ok(pageRules.groups.filter(group=>group.chat).every(group=>group.selector.startsWith('#chatRoot')));
assert.ok(!/nth-child|nth-of-type|___[a-zA-Z0-9]/.test(pageRules.css),'No positional chat rules or captured hash suffixes.');
for(const block of pageRules.css.matchAll(/\\{([^}]+)\\}/g))for(const declaration of block[1].split(';').filter(Boolean))assert.ok(/^(background-color|color):/.test(declaration),'Page-specific additions must not alter layout, images or stateful controls.');
assert.equal(api.normalize().enabled,false,'Never change defaults for existing users.');
assert.equal(api.normalize({enabled:'true'}).enabled,false);
assert.equal(api.normalize({opacity:-1}).opacity,0);assert.equal(api.normalize({opacity:999}).opacity,100);
assert.equal(api.normalize({opacity:'no'}).opacity,92);
assert.equal(api.asset('url("https://evil.test/frame.png")'),'none');
assert.equal(api.asset('url("javascript:alert(1)")'),'none');
assert.equal(api.asset('url("https://raw.githubusercontent.com/Considious/SLINK-Cloudflare-Services/main/themes/assets/a.png?x=1")'),'none');
const background='url("https://raw.githubusercontent.com/Considious/SLINK-Cloudflare-Services/main/themes/assets/halloween-2026-background.png")';
assert.equal(api.asset(background),background);
const result=api.compile({theme:{tokens:{'--slink-bg':'red;}body{display:none','--slink-text':'#fefefe'}},settings:{enabled:true,opacity:37},assetCss:{'--slink-theme-background-image':background}});
assert.equal(result.hasImage,true);assert.ok(!result.css.includes('display:none'));assert.ok(result.css.includes('--slt-bg:#121922'));assert.ok(result.css.includes('37%,transparent'));
assert.ok(result.css.includes('--appheader-dropdown-background'),'Include the neutral native-variable map, not just a few container colors.');
assert.ok(!result.css.includes('backdrop-filter'));assert.ok(!result.css.includes('transform:'));assert.ok(!result.css.includes('z-index:'));
assert.ok(!/querySelectorAll|fetch\(|XMLHttpRequest|setInterval|requestAnimationFrame/.test(source.slice(0,source.indexOf('function mountSettings'))),'Engine must not scan Torn, scrape, poll or fetch scripts. Settings may query their own controls.');
assert.ok(source.includes('childList:true')&&!source.includes('subtree:true'),'Observer must not watch all Torn mutations.');
console.log('Torn theme: opt-in defaults, numeric settings, strict assets, CSS injection guard and no DOM polling/scraping passed.');
